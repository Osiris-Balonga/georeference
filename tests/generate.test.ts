import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp,rm,readdir,readFile,writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { generateFiles } from '../src/generate.ts';
import { readResourcePackage as readPackage } from '../src/domain/package.ts';
const row=(iso:string,iso3:string,id:string)=>[iso,iso3,'001','','Synthetic test country','','','','','','','','','','','',id].join('\t')+'\n';
test('default generation is offline and ships real Congo relationships with verifiable coverage',async t=>{
  const folder=await mkdtemp(join(tmpdir(),'georeference-generate-'));t.after(()=>rm(folder,{recursive:true,force:true}));
  const output=join(folder,'out');
  const manifest=await generateFiles({output,request:{format:'json',audit:true}});
  assert.equal(manifest.geographicCoverage,'partial');assert.match(manifest.datasetVersion,/^cg-reference-/);
  const imported=await readPackage(output);
  assert.ok(imported.tables.arrondissements.some(e=>e.name==='Bacongo'));
  assert.ok(imported.tables.neighborhoods.some(e=>e.name==='Mpila'));
  assert.deepEqual(imported.tables.countries.map(e=>e.iso2),['CG']);
  const coverage=JSON.parse(await readFile(join(output,'coverage.json'),'utf8'));
  assert.equal(coverage.status,'partial');assert.equal(coverage.selection.count,manifest.count);
  const provenance=JSON.parse(await readFile(join(output,'provenance.json'),'utf8'));
  assert.ok(provenance.entities[imported.tables.communes.find(e=>e.name==='Brazzaville')!.id].evidence.length);
  assert.deepEqual(await readdir(folder),['out']);
});
test('city and arrondissement filters select verified descendants and preserve parent context',async t=>{
  const folder=await mkdtemp(join(tmpdir(),'georeference-city-'));t.after(()=>rm(folder,{recursive:true,force:true}));
  const output=join(folder,'out');
  await generateFiles({output,request:{format:'json',kinds:['neighborhood'],audit:true},city:'Brazzaville',arrondissement:'6'});
  const imported=await readPackage(output);const names=Object.values(imported.tables).flat().map(e=>e.name);
  assert.ok(names.includes('Mpila'));assert.ok(names.includes('Talangaï'));assert.ok(!names.includes('Pointe-Noire'));
  const coverage=JSON.parse(await readFile(join(output,'coverage.json'),'utf8'));
  assert.ok(coverage.selection.count<coverage.referenceCounts.neighborhood);
  const provenance=JSON.parse(await readFile(join(output,'provenance.json'),'utf8'));
  assert.equal(Object.keys(provenance.entities).length,imported.manifest.count);
  await assert.rejects(generateFiles({output:join(folder,'bad'),request:{format:'json'},arrondissement:'1'}),/--city/);
  await assert.rejects(generateFiles({output:join(folder,'bad'),request:{format:'json'},city:'Pointe-Noire',arrondissement:'Talangaï'}),/arrondissement/);
});
test('Congo-only input rejects foreign requests, malformed local sources and cancellation atomically',async t=>{
  const folder=await mkdtemp(join(tmpdir(),'georeference-generate-fail-'));t.after(()=>rm(folder,{recursive:true,force:true}));
  const options={output:join(folder,'out'),request:{format:'json'}};
  for(const code of ['CD','COD','FR'])await assert.rejects(generateFiles({...options,request:{format:'json',countries:[code]}}),/Congo|CG/);
  const source=join(folder,'countryInfo.txt');
  await writeFile(source,'not tabular data');await assert.rejects(generateFiles({...options,sourceFile:source}),/columns/);
  await writeFile(source,'x'.repeat(2*1024*1024+1));await assert.rejects(generateFiles({...options,sourceFile:source}),/2 MiB/);
  await writeFile(source,row('CD','COD','203'));
  await assert.rejects(generateFiles({...options,sourceFile:source}),/Congo|CG/);
  await writeFile(source,row('CG','COG','2260494')+row('CD','COD','203'));
  const manifest=await generateFiles({...options,request:{format:'json',audit:true},sourceFile:source});assert.equal(manifest.count,1);
  assert.match(manifest.datasetVersion,/geonames/);assert.equal(manifest.geographicCoverage,'partial');
  const coverage=JSON.parse(await readFile(join(options.output,'coverage.json'),'utf8'));assert.equal(coverage.status,'unverified');
  const controller=new AbortController();controller.abort();
  await assert.rejects(generateFiles({...options,output:join(folder,'cancelled'),signal:controller.signal}),{name:'AbortError'});
  assert.deepEqual((await readdir(folder)).sort(),['countryInfo.txt','out']);
});
